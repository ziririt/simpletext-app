/// 선택 핸들을 잡았다고 볼 만한 거리.
///
/// 2026-09-07 에 만든 '핸들 끌기 동안 바깥 스크롤 잠그기'(main.dart 의
/// `_selHandleDrag` 머리말)가 **한 손에서만 걸리던 일**을 고치면서 이 파일이
/// 생겼다.
///
/// 소유자 신고 — "왼쪽 엄지로 핸들링을 잡고 우측으로 드래그하려고 하면
/// 핸들이 안 잡히고, 오른쪽 엄지로 핸들을 잡고 우측으로 드래그하면 이건
/// 된다. 너무 불편하다."
///
/// ## 왜 손에 따라 갈렸나
///
/// **화면이 받는 점은 사람이 겨눈 점이 아니다.** 엄지로 화면을 누르면 닿는
/// 것은 점이 아니라 타원이고, 기기가 돌려주는 좌표는 그 타원의 무게중심이다.
/// 그런데 엄지는 **손목 쪽에서 뻗어 나오므로** 무게중심이 늘 **뻗어 온
/// 쪽으로 치우친다.**
///
///   왼손 엄지로 오른쪽을 겨누면 → 받는 점은 겨눈 곳보다 **왼쪽·아래**
///   오른손 엄지로 오른쪽을 겨누면 → 받는 점은 겨눈 곳에 가깝거나 오른쪽
///
/// 예전 상자는 가로 36pt 였다. 오른손은 그 안에 들어오고 왼손은 벗어난다.
/// 벗어나면 잠금이 안 걸리고, 잠금이 안 걸리면 바깥 스크롤이 손가락을
/// 가져간다 — **핸들이 "안 잡히는" 것처럼 보이는 것의 정체가 이것이다.**
/// 핸들이 작아서가 아니라 우리 상자가 좁아서였다.
///
/// ## 그래서 넉넉히 본다
///
/// 가로 60, 세로 72. 넓혀서 잃는 것은 거의 없다 — 이 셈은 **블록이 잡혀
/// 있을 때만** 돌고, 그때 핸들 곁을 누르는 손짓은 열에 아홉 '핸들을 잡으려는
/// 것'이다. 잘못 걸려도 손가락을 떼면 바로 풀린다.
///
/// > **손가락은 점이 아니다.** 손으로 겨누는 조작점의 판정 상자는, 눈으로
/// > 보이는 크기가 아니라 **어느 쪽에서 손이 오는지**까지 담아야 한다.
library;

import 'dart:ui' show Offset;

/// 핸들 좌우로 이만큼까지는 '잡으려는 것'으로 본다.
const double kHandleGrabX = 60;

/// 핸들 위아래로 이만큼까지. 핸들은 줄 위(시작)와 아래(끝)로 튀어나와
/// 있어서 세로를 더 넉넉히 둔다.
const double kHandleGrabY = 72;

/// 손가락이 핸들 가운데 하나라도 가까운가.
bool nearAnyHandle(
  Offset finger,
  Iterable<Offset> handles, {
  double dx = kHandleGrabX,
  double dy = kHandleGrabY,
}) {
  for (final h in handles) {
    if ((h.dx - finger.dx).abs() <= dx && (h.dy - finger.dy).abs() <= dy) {
      return true;
    }
  }
  return false;
}
