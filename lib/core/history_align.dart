/// 짝이 안 맞는 곁줄에서 값 꺼내기 — 버전 기록이 남긴 오래된 숙제.
///
/// 2026-08-19. 버전 기록은 줄 셋으로 되어 있다.
///
///   history     이전 판의 글    ← 이게 본줄
///   historyAt   그때의 시각     ← 곁줄
///   historyWhy  왜 남았나       ← 곁줄 (오늘 새로 붙였다)
///
/// 곁줄은 본줄보다 **나중에** 생겼다. 그래서 옛 저장본에는 본줄만 있고
/// 곁줄이 아예 없거나 짧다. 문제는 여기서 시작된다.
///
/// ## 앞에서부터 세면 틀린다
///
/// 기록이 서른을 넘으면 **맨 앞을 버린다.** 그러니 두 줄이 짝을 이루는
/// 지점은 앞이 아니라 **뒤**다. 옛 판 셋에 곁줄이 없는 메모에 새 판 하나가
/// 들어오면 본줄 넷, 곁줄 하나가 되는데, 그 하나는 넷째 것의 짝이다.
/// 앞에서부터 세면 그 하나를 **첫째의 짝**으로 읽는다 — 오늘 남긴 시각이
/// 몇 달 전 판에 붙는다.
///
/// 여태 그렇게 읽고 있었다(`i < historyAt.length ? historyAt[i] : 0`).
/// 곁줄이 하나뿐이라 눈에 안 띄었을 뿐이다. 곁줄을 하나 더 붙이는 김에
/// 판정을 여기로 옮기고 시험으로 못 박는다.
library;

/// 본줄의 [i]번째와 짝을 이루는 곁줄 값. 짝이 없으면 null.
///
/// 두 줄을 **끝에서부터** 맞춘다. 곁줄이 본줄보다 길면(있어서는 안 되지만
/// 남의 기기에서 온 자료라면 있을 수 있다) 남는 앞부분은 버린다.
T? sideValue<T>(List<T> side, int mainLength, int i) {
  if (i < 0 || i >= mainLength) return null;
  final offset = mainLength - side.length;
  final k = i - offset;
  if (k < 0 || k >= side.length) return null;
  return side[k];
}
