String _stripParticle(String w) {
  for (final s in _particles) {
    if (w.length > s.length + 1 && w.endsWith(s)) {
      return w.substring(0, w.length - s.length);
    }
  }
  return w;
}

bool _endsWithVerbEnding(String w) {
  for (final e in _verbEndings) {
    // 어미만 남는 것은 어미가 아니다("하기" 자체는 두 글자라 통째로 걸린다).
    if (w.length >= e.length + 1 && w.endsWith(e)) return true;
  }
  return false;
}

// ── 한자음 규칙 ────────────────────────────────────────────────────────
//
// 한국어에서 두 글자 이름은 대개 한자어다. 한자음에는 없는 소리가 있고,
// 그 소리가 들어간 음절은 고유어다. 고유어 한 음절 + 관형형 어미는
// 십중팔구 용언의 활용형이다('꺾인', '굽은', '익은').
//
//   첫소리에 없는 것: ㄲ ㄸ ㅃ ㅆ ㅉ (된소리)
//   받침에 있는 것 :  없음 · ㄱ ㄴ ㄹ ㅁ ㅂ ㅇ  — 이 여섯뿐이다
//
// 완벽한 규칙은 아니다. 다만 틀렸을 때의 대가가 작다 — 태그 하나가 덜
// 나올 뿐이고, 태그는 사용자가 직접 더할 수 있다.
const int _hangulBase = 0xAC00;
const int _hangulLast = 0xD7A3;
const Set<int> _tenseInitials = {1, 4, 8, 10, 13}; // ㄲ ㄸ ㅃ ㅆ ㅉ
const Set<int> _sinoFinals = {0, 1, 4, 8, 16, 17, 21}; // 없음 ㄱ ㄴ ㄹ ㅁ ㅂ ㅇ

bool _looksSino(int code) {
  if (code < _hangulBase || code > _hangulLast) return false;
  final i = code - _hangulBase;
  if (_tenseInitials.contains(i ~/ 588)) return false;
  return _sinoFinals.contains(i % 28);
}

/// 관형형 어미로 끝나는 한 음절들. 앞 음절이 고유어면 용언으로 본다.
const Set<String> _adnominalTail = {
  '인', '은', '운', '른', '린', '한', '된', '난', '든', '진', '킨', '긴',
  '친', '힌', '는', '을', '던',
};

/// '꺾인' 같은 두 글자 용언 활용형인가.
bool _looksNativeVerb(String w) {
  if (w.length != 2) return false;
  if (!_adnominalTail.contains(w[1])) return false;
  return !_looksSino(w.codeUnitAt(0));
}

final RegExp _splitter = RegExp(r'[^0-9A-Za-z가-힣]+');
final RegExp _startsDigit = RegExp(r'^[0-9]');

/// [title]과 [body](앞부분만 넘길 것)에서 태그 후보를 [max]개까지 고른다.
List<String> suggestTags(String title, String body, {int max = 5}) {
  final scores = <String, int>{};
  final bodyHits = <String, int>{};
  final display = <String, String>{};

  void feed(String text, int weight, {required bool isBody}) {
    for (final raw in text.split(_splitter)) {
      if (raw.isEmpty) continue;
      if (_startsDigit.hasMatch(raw)) continue; // 45, 2036년, 20% 같은 것
      final w = _stripParticle(raw);
      if (w.length < 2 || w.length > 20) continue;
      final key = w.toLowerCase();
      if (_stop.contains(key)) continue;
      if (_endsWithVerbEnding(w)) continue;
      if (_looksNativeVerb(w)) continue;
      scores[key] = (scores[key] ?? 0) + weight;
      if (isBody) bodyHits[key] = (bodyHits[key] ?? 0) + 1;
      // 표기는 처음 본 형태를 쓴다(AI, ChatGPT 같은 대문자 보존)
      display[key] ??= w;
    }
  }

  // 제목 가중치를 3에서 2로 낮췄다(2026-08-17). 이 앱은 제목을 본문 첫
  // 줄에서 자동으로 짓는다. 그러니 3배를 주면 첫 줄의 낱말이 글 전체의
  // 주제를 밀어내고 태그를 독식한다.
  feed(title, 2, isBody: false);
  feed(body, 1, isBody: true);
  if (scores.isEmpty) return const [];

  // 본문에 두 번 이상 나온 말이 충분하면 그것만 쓴다.
  //
  // 한 번 스친 낱말과 글 내내 되풀이되는 낱말은 무게가 다르다. 되풀이되는
  // 쪽이 곧 그 글의 주제다. 다만 짧은 메모에서는 두 번 나오는 말이 아예
  // 없을 수 있으므로, 충분할 때만 이 체를 쓴다.
  final repeated = scores.keys.where((k) => (bodyHits[k] ?? 0) >= 2).toList();
  final pool = repeated.length >= max ? repeated : scores.keys.toList();

  final keys = pool.toList()
    ..sort((a, b) {
      final d = scores[b]!.compareTo(scores[a]!);
      if (d != 0) return d;
      final e = b.length.compareTo(a.length);
      if (e != 0) return e;
      return a.compareTo(b);
    });
  return keys.take(max).map((k) => display[k]!).toList();
}
