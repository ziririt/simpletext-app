/// 본문에서 태그 후보를 골라내는 순수 함수.
///
/// 2026-08-14 소유자 요청: 편집기에 "태그 AI 자동입력" 버튼을 넣는다.
/// 소유자 확정 사항 — **버튼은 AI 키가 없어도 항상 동작해야 한다.**
/// 키가 있으면 AI가 뽑고, 키가 없거나 호출이 실패하면 이 함수가 대신 뽑는다.
/// 이 앱의 제1원칙이 Local First(AI는 옵션)이므로 이쪽이 원칙에 맞다.
///
/// 그리고 배경에서 조용히 도는 자동 태그는 **언제나 이 함수만** 쓴다.
/// 글자를 칠 때마다 AI를 부르면 사용자 요금이 샌다. 그래서 이 파일의 품질이
/// 곧 대부분의 사용자가 보는 태그의 품질이다.
///
/// 이건 정리 엔진이 아니다. 앱 전용 보조 기능이라 웹에 대칭 구현이 없다.
///
/// ## 2026-08-17 — 다시 씀
///
/// 소유자 신고: "자동 태그. 제목만 분석하냐? 안된다. 그리고 과연 이게 무슨
/// 핵심 태그냐. 동사는 특히 안된다." 화면에 붙어 있던 것이 이랬다.
///
///     소비 · 해야하는데 · 국채금리 · AI · 꺾인
///
/// 다섯 중 둘이 동사 활용형이다. '해야하는데'와 '꺾인'은 태그가 아니라
/// 문장 조각이고, 저런 것이 붙어 있으면 나머지 셋까지 못 미더워진다.
///
/// 까닭은 이 파일이 **낱말을 셀 줄만 알고 이름인지 아닌지는 몰랐던 것**이다.
/// 조사만 떼고 나머지는 전부 후보로 삼았다. 태그는 '이 글이 무엇에 관한
/// 것인가'를 가리키는 이름이라, 움직임을 나타내는 말은 처음부터 후보가
/// 아니어야 한다.
///
/// 형태소 분석기를 넣지 않은 것은 그대로다. 대신 규칙 셋을 뒀다.
///
///   1) 어미로 끝나면 버린다 — '…하는데', '…지만', '…해야' 같은 것들.
///      두 글자 이상인 어미만 본다. 한 글자(고·지·서·요·인)로 자르면
///      보고·이미지·문서·수요·확인 같은 멀쩡한 이름이 같이 죽는다.
///
///   2) 두 글자짜리 '어간+관형형' 꼴을 한자음 규칙으로 걸러낸다.
///      '꺾인'이 여기서 걸린다 — '꺾'의 받침 ㄲ은 한자음에 없는 소리라
///      고유어 어간이고, 뒤에 관형형 어미가 붙었으면 그건 용언이다.
///      '확인'·'원인'·'요인'은 첫 음절이 한자음 꼴이라 살아남는다.
///
///   3) 흔한 관형형·부사는 목록으로 막는다. 규칙으로 잡기 어려운 것들
///      ('작은', '많은')은 이름을 적어 두는 편이 정직하다.
///
/// 그리고 제목만 보는 것이 아니다. 제목과 본문 앞부분을 함께 보되 제목에
/// 가중치를 준다. 다만 가중치를 3에서 2로 낮췄다 — 제목은 본문 첫 줄을
/// 그대로 따라가는 경우가 많아서, 3배를 주면 첫 줄이 태그를 독식한다.
