/// 앱 버전 — 화면에 보여 주기 위한 값.
///
/// 2026-08-12 소유자 요청: "항상 버전 업데이트를 해라. 그래야 제대로 업데이트가
/// 반영되었는지 정확히 알 수 있다." 맞는 지적이라 규칙으로 삼는다.
///
/// 중요한 점 두 가지:
///   1) 버전은 올리기만 해서는 소용이 없다. 앱 안에서 눈으로 볼 수 있어야
///      "지금 깔린 게 새 버전인지"를 확인할 수 있다. 설정 화면 맨 아래에 표시한다.
///   2) 웹과 앱은 같은 제품이므로 **같은 버전 번호**를 쓴다. 두 개를 따로 세면
///      어느 쪽이 최신인지 사람이 매번 헷갈린다.
///
/// 값을 바꿀 때는 pubspec.yaml의 version:도 같이 바꿔야 한다.
/// 어긋나면 tool/version_check.py가 CI에서 실패로 잡는다.
/// 웹(simpletext/index.html)의 APP_VERSION도 함께 맞춘다.
library;

/// 사람이 보는 버전. 기능이 바뀌면 가운데 자리, 고침만 있으면 끝자리를 올린다.
const String appVersion = '1.0.16';

/// 빌드 번호. 같은 버전으로 여러 번 올릴 때 구분한다.
/// TestFlight 업로드 시에는 CI가 실행 번호로 덮어쓴다(같은 번호를 두 번 못 받기 때문).
// 2026-08-17 — 이 번호는 **절대 내리지 않는다.**
//
// 아이클라우드 자리를 설정 앱 목록에 보이게 하는 값(NSUbiquitousContainers)을
// 0.3.38.1에서 넣었는데도 목록에 안 떴다. 까닭은 애플 문서에 있다 — iOS는
// 그 값을 앱을 처음 깔 때 한 번 읽고, 그 뒤로는 **빌드 번호가 올라갈 때만**
// 다시 읽는다.
//
// 우리 빌드 번호는 여러 판을 거치는 동안 계속 1이었고, 0.3.36.2에서 잠깐
// 2가 됐다가 0.3.37에서 다시 1로 내려갔다. 앞자리만 올라갔지 iOS가 보는
// 번호는 그대로였다. 그러니 새 Info.plist를 읽을 이유가 없었다.
//
// 앞자리를 올릴 때 이 번호를 1로 되돌리는 습관이 원인이었다. 그 습관을
// 버린다. 판이 바뀌든 안 바뀌든 여기는 늘 오른다.
const int appBuild = 90;

/// 화면에 그대로 찍히는 문자열. 소유자 지정 형식(2026-08-12): ver.0.1.1.1 꼴
/// 앞 세 자리는 pubspec의 version, 마지막 자리는 빌드 번호다.
String get appVersionLabel => 'ver.$appVersion.$appBuild';
