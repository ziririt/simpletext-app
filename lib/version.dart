/// 이 앱의 버전은 **앱스토어에 보이는 이름 하나**다. (2026-09-12 개편)
///
/// 소유자 지시 — "나도 헷갈리더라. **앱스토어 기준으로 바꿔라.**"
///
/// ── 그 전까지 무엇이 문제였나 ────────────────────────────────────────
///
/// 이름이 둘이었다. 앱스토어 화면에는 **1.7**, 앱 설정에는 **3.17.22.244**.
/// 같은 앱인데 부르는 이름이 둘이니 사람이 헷갈렸고, 실제로 사고가 났다.
///
///   · 2026-09-10 — 소유자가 옛 판(빌드 223)을 쓰면서 최신인 줄 알고
///     "아직도 안 고쳐졌다"고 신고했다. 두 이름 중 어느 것을 봐야 하는지
///     화면이 말해 주지 않았기 때문이다(HANDOFF 3.12).
///   · 2026-09-11 — '최신 버전 확인'을 만들 때, 애플이 돌려주는 이름은
///     1.7 인데 앱이 아는 이름은 3.17.22 라 그냥 견주면 **영원히
///     "최신입니다"** 라고 답하는 앱이 될 뻔했다.
///
/// 그때는 `kStoreVersion` 이라는 쪽지를 하나 더 들려서 막았다. 쪽지가
/// 하나 더 는 것이지 헷갈림이 준 것은 아니었다. 그래서 이름을 하나로 줄인다.
///
/// **사람이 말하고 보는 이름은 이제 하나다 — 앱스토어의 그 이름.**
///
/// ── 2026-09-12 오후, 한 걸음 더 (이름을 진짜로 하나로) ────────────────
///
/// 위의 개편에서도 값은 둘이었다. 사람이 보는 1.7 과, 꾸러미 안에만 있던
/// 기계용 3.245.0. 소유자 판단 — "이럴 바에는 그냥 맞춰서 시작하는 건
/// 어떠냐? **완전히 다 일치시키는 것이지.** 사실 1.8도 사용자에게는 아무
/// 의미가 없다. 너와 나만 인정하고 앱스토어 심사만 통과 잘 되면 된다."
///
/// 옳다. 그래서 **스토어 이름과 꾸러미 값을 같은 값으로** 만든다.
///
/// 다만 아무 숫자나 못 쓴다. 애플은 꾸러미 값을 못 내리게 하고(ITMS-90062),
/// 지금까지 올린 것 중 가장 큰 것이 **3.17.22** 다. 그래서 새 이름은
/// 3.17.22 보다 커야 한다.
///
/// **여기 함정이 있다.** 소유자가 처음 말한 '3.3' 은 못 쓴다. 애플은
/// 3.3 을 '삼 점 삼'이라는 소수로 읽지 않고 **자리마다 숫자로** 읽는다.
///
///     3.3    → (3, 3)
///     3.17.22 → (3, 17, 22)
///     둘째 자리를 견주면 3 < 17 — **3.3 은 3.17.22 보다 작다.**
///
/// 그래서 3.18 부터 간다. 3.17.22 보다 크고, 1.7 보다도 크다.
/// 다음은 3.19, 3.20 … 이다. 자릿수가 아니라 숫자로 오른다.
library;

/// 이 앱의 버전. **딱 하나다.**
///
/// 앱스토어 화면, 설정 화면, 꾸러미 안 — 전부 이 값이다.
/// 새 판을 스토어에 낼 때 이것만 올린다. `pubspec.yaml` 의 version 도
/// 같은 값이어야 하고, 어긋나면 `tool/version_check.py` 가 잡는다.
const String appVersion = '3.18';

/// 빌드 번호. 같은 이름으로 여러 번 올릴 때 구분한다.
///
/// 2026-08-17 — 이 번호는 **절대 안 내린다.**
///
/// 아이클라우드 자리를 설정 앱 목록에 보이게 하는 값(NSUbiquitousContainers)을
/// 넣었는데도 목록에 안 떴다. 까닭은 애플 문서에 있다 — iOS 는 그 값을 앱을
/// 처음 깔 때 한 번 읽고, 그 뒤로는 **빌드 번호가 올라갈 때만** 다시 읽는다.
/// 앞자리를 올릴 때 이 번호를 1로 되돌리는 습관이 원인이었다. 그 습관을
/// 버린다. 판이 바뀌든 안 바뀌든 여기는 늘 오른다.
const int appBuild = 246;

/// 화면에 그대로 찍히는 문자열. 예: `ver.3.18 (246)`
///
/// 앞은 앱스토어에 보이는 그 이름, 괄호 안은 빌드 번호다. 스토어에 나간 판과
/// 지금 깔린 판이 같은 이름이어도 빌드 번호로 갈라 볼 수 있다.
String get appVersionLabel => 'ver.$appVersion ($appBuild)';

/// `pubspec.yaml` 의 version 에 적을 값. 애플·구글은 세 자리를 원한다.
/// 3.18 → 3.18.0
String get pubspecVersionName =>
    appVersion.split('.').length >= 3 ? appVersion : '$appVersion.0';
