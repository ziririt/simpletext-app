/// 이 앱의 버전은 **앱스토어에 보이는 이름 하나**다. (2026-09-12 개편)
///
/// 소유자 지시 — "나도 헷갈리더라. **앱스토어 기준으로 바꿔라.**"
///
/// ── 그 전까지 무엇이 문제였나 ────────────────────────────────────────
///
/// 이름이 둘이었다. 앱스토어 화면에는 **1.7**, 앱 설정에는 **3.17.22.244**.
/// 같은 앱인데 부르는 이름이 둘이니 사람이 헷갈렸고, 실제로 사고가 났다.
///
///   · 2026-09-10 — 소유자가 옛 판(빌드 223)을 쓰면서 최신인 줄 알고
///     "아직도 안 고쳐졌다"고 신고했다. 두 이름 중 어느 것을 봐야 하는지
///     화면이 말해 주지 않았기 때문이다(HANDOFF 3.12).
///   · 2026-09-11 — '최신 버전 확인'을 만들 때, 애플이 돌려주는 이름은
///     1.7 인데 앱이 아는 이름은 3.17.22 라 그냥 견주면 **영원히
///     "최신입니다"** 라고 답하는 앱이 될 뻔했다.
///
/// 그때는 `kStoreVersion` 이라는 쪽지를 하나 더 들려서 막았다. 쪽지가
/// 하나 더 는 것이지 헷갈림이 준 것은 아니었다. 그래서 이름을 하나로 줄인다.
///
/// **사람이 말하고 보는 이름은 이제 하나다 — 앱스토어의 그 이름.**
library;

/// 앱스토어에 보이는 이름. 설정 화면에도 이것이 찍힌다.
///
/// 새 판을 스토어에 낼 때 **이 값 하나만** 올리면 된다. 안 올리고 구우면
/// `tool/appstore_ios.sh` 가 애플에게 물어보고 굽기 전에 멈춘다.
const String appVersion = '1.7';

/// 빌드 번호. 같은 이름으로 여러 번 올릴 때 구분한다.
///
/// 2026-08-17 — 이 번호는 **절대 안 내린다.**
///
/// 아이클라우드 자리를 설정 앱 목록에 보이게 하는 값(NSUbiquitousContainers)을
/// 넣었는데도 목록에 안 떴다. 까닭은 애플 문서에 있다 — iOS 는 그 값을 앱을
/// 처음 깔 때 한 번 읽고, 그 뒤로는 **빌드 번호가 올라갈 때만** 다시 읽는다.
/// 우리 빌드 번호는 여러 판을 거치는 동안 계속 1이었고 잠깐 2가 됐다가 다시
/// 1로 내려갔다. 앞자리만 올라갔지 iOS 가 보는 번호는 그대로였다.
/// 앞자리를 올릴 때 이 번호를 1로 되돌리는 습관이 원인이었다. 그 습관을
/// 버린다. 판이 바뀌든 안 바뀌든 여기는 늘 오른다.
const int appBuild = 245;

/// 화면에 그대로 찍히는 문자열. 예: `ver.1.7 (245)`
///
/// 앞은 앱스토어에 보이는 이름, 괄호 안은 빌드 번호다. 스토어에 나간 판과
/// 지금 깔린 판이 같은 이름이어도 빌드 번호로 갈라 볼 수 있다.
String get appVersionLabel => 'ver.$appVersion ($appBuild)';

// ── 여기부터는 기계만 보는 값이다. 사람은 신경 쓸 것 없다 ──────────────
//
// 애플은 꾸러미 안의 마케팅 버전(CFBundleShortVersionString)이 **이전에
// 올린 것보다 커야** 업로드를 받는다.
//
//   ERROR ITMS-90062: the value for key CFBundleShortVersionString
//   must contain a higher version than that of the previously approved version
//
// 우리가 지금까지 올린 것 중 가장 큰 것이 3.17.22 다. 이제 와서 그 자리에
// 1.8 을 넣으면 애플이 거부한다. **번호는 내려갈 수 없다.** 스토어 이름을
// 그대로 꾸러미에 넣지 못하는 이유가 이것이고, 이 값이 따로 있는 이유다.
//
// 그래서 그 자리에는 **빌드 번호에서 자동으로 만든 값**을 넣는다.
//
//     pubspec.yaml 의  version: 3.<빌드>.0+<빌드>
//
// 빌드 번호는 늘 오르니 이 값도 늘 오른다. 사람이 정할 것이 없다. 어긋나면
// tool/version_check.py 가 잡는다. 이 값은 **어느 화면에도 안 나온다** —
// 아이폰 꾸러미 안에만 있다. 안드로이드는 build.gradle 에서 따로 스토어
// 이름을 쓰게 해 뒀다(구글은 이런 제약이 없다).

/// 꾸러미에 들어갈 마케팅 버전. pubspec.yaml 의 version 과 같아야 한다.
String get bundleVersionName => '3.$appBuild.0';
